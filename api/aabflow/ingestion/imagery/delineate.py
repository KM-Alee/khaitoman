"""Delineate Anything inference runner (T2.4 steps 5-6).

Inference is keyed by content: ``inference_key = sha256(input raster, base config,
checkpoint id, upstream commit)``. The runner

1. prepares ``vision/runs/<key>/input/<entry>/scene.tif`` and the batch file
   ``vision/batches/<key>.yaml`` (upstream format, ``python delineate.py -b``),
2. executes the vision container when a Docker CLI is reachable (host / Make), or
   reports that the matching inference must be run (the API container has no
   Docker socket), and
3. collects the untouched output GeoPackage into GeoJSON with model ids.

A completed run is reused by key (a disclosed content-hash cache hit, T2.6).
"""

from __future__ import annotations

import json
import math
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from aabflow.domain.hashes import content_hash, file_sha256

from ..common import IngestionError, read_json

VISION_DIR_IN_CONTAINER = "/app/vision"
CHECKPOINT = "/app/data/models/delineate-anything/DelineateAnythingv2.pt"
CHECKPOINT_ID = "MykolaL/DelineateAnything:DelineateAnythingv2.pt"
BASE_CONFIG = "configs/conf_pilot_s2_sr4.yaml"
UPSTREAM_COMMIT = "4cfab87ecccbe8d1bda4167676f623e3728570d9"
ENTRY = "scene"
COMPOSE_CMD = [
    "docker",
    "compose",
    "-f",
    "compose.yaml",
    "-f",
    "vision/compose.vision.yaml",
    "--profile",
    "vision",
    "run",
    "--rm",
    "--no-deps",
    "-T",
    "vision",
]


class InferencePending(IngestionError):
    """The matching inference has not been executed yet (needs the vision container)."""

    def __init__(self, key: str, command: str):
        super().__init__(f"Delineate inference {key} not run yet; run: {command}")
        self.key = key
        self.command = command


@dataclass
class InferenceJob:
    key: str
    repo_root: Path
    input_tif: Path
    batch_yaml: Path
    run_dir: Path

    @property
    def output_gpkg(self) -> Path:
        return self.run_dir / "output" / f"{ENTRY}.gpkg"

    @property
    def record(self) -> Path:
        return self.run_dir / "run.json"

    def container_path(self, p: Path) -> str:
        return "/app/" + str(p.resolve().relative_to(self.repo_root.resolve()))

    def command(self) -> list[str]:
        return [
            *COMPOSE_CMD,
            "python",
            f"{VISION_DIR_IN_CONTAINER}/run_batch.py",
            self.container_path(self.batch_yaml),
            "--record",
            self.container_path(self.record),
            "--label",
            self.key,
        ]

    def command_str(self) -> str:
        return " ".join(self.command())

    def done(self) -> bool:
        if not (self.record.exists() and self.output_gpkg.exists()):
            return False
        rec = read_json(self.record)
        return bool(rec.get("ok"))


def inference_key(input_tif: Path, repo_root: Path) -> str:
    cfg = repo_root / "vision" / BASE_CONFIG
    return content_hash(
        {
            "input_sha256": file_sha256(input_tif),
            "base_config_sha256": file_sha256(cfg),
            "checkpoint": CHECKPOINT_ID,
            "upstream_commit": UPSTREAM_COMMIT,
        }
    )[:16]


def prepare(input_tif: Path, repo_root: Path) -> InferenceJob:
    """Stage the input raster and write the upstream-format batch file."""
    repo_root = Path(repo_root)
    key = inference_key(input_tif, repo_root)
    run_dir = repo_root / "vision" / "runs" / key
    dst = run_dir / "input" / ENTRY / "scene.tif"
    if not dst.exists():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(input_tif, dst)
    elif file_sha256(dst) != file_sha256(input_tif):
        raise IngestionError(f"staged inference input for {key} differs from source raster")
    job = InferenceJob(
        key, repo_root, dst, repo_root / "vision" / "batches" / f"{key}.yaml", run_dir
    )
    batch = {
        "base_config": f"{VISION_DIR_IN_CONTAINER}/{BASE_CONFIG}",
        "data_root": job.container_path(run_dir / "input"),
        "output_root": job.container_path(run_dir / "output"),
        "temp_root": f"/tmp/delineate-temp-{key}",
        "keep_temp": False,
        "mask_root": job.container_path(run_dir / "masks"),
        "include": [ENTRY],
        "exclude": None,
        "override": None,
    }
    job.batch_yaml.parent.mkdir(parents=True, exist_ok=True)
    # JSON is valid YAML 1.2 and avoids a YAML writer dependency in the api image.
    job.batch_yaml.write_text(
        "# Generated by aabflow.ingestion.imagery.delineate (upstream batch format)\n"
        + json.dumps(batch, indent=2)
        + "\n"
    )
    return job


def docker_available() -> bool:
    return shutil.which("docker") is not None


def run(job: InferenceJob, timeout_s: int = 3600) -> dict:
    """Execute (or reuse) the inference. Returns the run record."""
    if job.done():
        rec = read_json(job.record)
        rec["cache_hit"] = True
        return rec
    if not docker_available():
        raise InferencePending(job.key, job.command_str())
    proc = subprocess.run(
        job.command(),
        cwd=job.repo_root,
        capture_output=True,
        text=True,
        timeout=timeout_s,
        check=False,
    )
    if proc.returncode != 0 or not job.done():
        raise IngestionError(
            f"Delineate inference {job.key} failed (rc={proc.returncode}): {proc.stderr[-2000:]}"
        )
    rec = read_json(job.record)
    rec["cache_hit"] = False
    return rec


def collect(job: InferenceJob) -> dict:
    """Untouched model output → GeoJSON FeatureCollection (source CRS kept in properties).

    Each feature gets a model id ``da:<key>:<fid>`` from the GeoPackage feature id.
    """
    import geopandas as gpd
    import pyogrio

    if not job.output_gpkg.exists():
        raise InferencePending(job.key, job.command_str())
    layers = [name for name, _ in pyogrio.list_layers(job.output_gpkg)]
    layer = "fields" if "fields" in layers else layers[0]
    gdf = gpd.read_file(job.output_gpkg, layer=layer, fid_as_index=True)
    src_crs = str(gdf.crs)
    out = gdf.to_crs("EPSG:4326")
    feats = []
    for fid, row in out.iterrows():
        props = {
            k: (None if isinstance(v, float) and math.isnan(v) else v)
            for k, v in row.drop(labels=out.geometry.name).items()
        }
        props = {k: (v.item() if hasattr(v, "item") else v) for k, v in props.items()}
        mid = f"da:{job.key}:{int(fid)}"
        feats.append(
            {
                "type": "Feature",
                "id": mid,
                "geometry": json.loads(gpd.GeoSeries([row.geometry]).to_json())["features"][0][
                    "geometry"
                ],
                "properties": {"model_id": mid, "gpkg_fid": int(fid), **props},
            }
        )
    return {
        "type": "FeatureCollection",
        "features": feats,
        "properties": {
            "inference_key": job.key,
            "source_layer": layer,
            "source_crs": src_crs,
            "output_crs": "EPSG:4326",
            "gpkg_sha256": file_sha256(job.output_gpkg),
            "checkpoint": CHECKPOINT_ID,
            "upstream_commit": UPSTREAM_COMMIT,
            "note": "Untouched Delineate Anything output (reprojected for display only).",
        },
    }
